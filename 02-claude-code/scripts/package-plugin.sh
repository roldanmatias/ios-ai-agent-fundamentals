#!/bin/bash
# Packages ListingsKit's .claude setup as an installable plugin, so any Swift package repo
# gets the same guardrails with one install. ListingsKit/.claude stays the source of truth;
# rerun this after changing it.
#
# Usage: scripts/package-plugin.sh [VERSION]
# Output: plugin/ios-swift-guardrails/ and .claude-plugin/marketplace.json (a local
# marketplace: `/plugin marketplace add ./02-claude-code`).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SOURCE="$ROOT/ListingsKit/.claude"
NAME=ios-swift-guardrails
PLUGIN="$ROOT/plugin/$NAME"
VERSION=${1:-0.1.0}

rm -rf "$PLUGIN"
mkdir -p "$PLUGIN/.claude-plugin" "$PLUGIN/hooks" "$PLUGIN/skills" "$PLUGIN/agents" "$ROOT/.claude-plugin"

cp "$SOURCE"/hooks/*.sh "$PLUGIN/hooks/"
cp -R "$SOURCE/skills/verify-swift" "$PLUGIN/skills/"
cp "$SOURCE/agents/swift-reviewer.md" "$PLUGIN/agents/"

# Project paths become plugin paths; ListingsKit-specific wording becomes generic.
jq '{hooks: .hooks}' "$SOURCE/settings.json" \
    | sed 's|\\"\$CLAUDE_PROJECT_DIR\\"/.claude/hooks/|\\"${CLAUDE_PLUGIN_ROOT}\\"/hooks/|g' \
    > "$PLUGIN/hooks/hooks.json"
sed -i '' \
    -e 's|Verify a change to ListingsKit|Verify a change to a Swift package|' \
    -e 's|Run `.claude/skills/verify-swift/check.sh`|Run `check.sh` from this skill'"'"'s base directory|' \
    "$PLUGIN/skills/verify-swift/SKILL.md"
sed -i '' -e 's|for ListingsKit changes|for Swift package changes|' -e 's|ListingsKit|the Swift package|g' "$PLUGIN/agents/swift-reviewer.md"
sed -i '' -e '/^## Common ListingsKit failures/,$d' "$PLUGIN/skills/verify-swift/reference.md"
sed -i '' -e 's|for ListingsKit|for a Swift package|' "$PLUGIN/skills/verify-swift/check.sh"

jq -n --arg name "$NAME" --arg version "$VERSION" '{
    name: $name,
    version: $version,
    description: "Guardrails for Claude Code in Swift packages: blocks edits that remove test assertions or add @unchecked Sendable, formats after every edit, refuses to stop on a red build, plus a verify-swift skill and a read-only swift-reviewer subagent.",
    author: {name: "Matias Roldan"},
    repository: "https://github.com/roldanmatias/ios-ai-agent-fundamentals",
    keywords: ["swift", "ios", "hooks", "testing", "guardrails"]
}' > "$PLUGIN/.claude-plugin/plugin.json"

jq -n --arg name "$NAME" --arg version "$VERSION" '{
    name: "ios-ai-agent-fundamentals",
    description: "Claude Code plugins for iOS and Swift package development.",
    owner: {name: "Matias Roldan"},
    plugins: [{
        name: $name,
        source: ("./plugin/" + $name),
        version: $version,
        description: "Swift package guardrails for Claude Code: hooks, a verification skill and a reviewer subagent."
    }]
}' > "$ROOT/.claude-plugin/marketplace.json"

cat > "$PLUGIN/README.md" <<EOF
# $NAME

Generated by \`scripts/package-plugin.sh\` from \`ListingsKit/.claude\`. Don't edit by hand.

| Piece | What it does |
| --- | --- |
| \`hooks/guard-edits.sh\` (PreToolUse) | Denies edits that remove \`#expect\` / \`#require\` / \`XCTAssert\` or add \`@unchecked Sendable\` / \`nonisolated(unsafe)\` |
| \`hooks/format-swift.sh\` (PostToolUse) | Runs \`swift format\` on the edited file and feeds lint findings back |
| \`hooks/stop-gate.sh\` (Stop) | Blocks the end of a turn while \`swift build\` or \`swift test\` fails, at most 3 times per session |
| \`hooks/restore-context.sh\` (SessionStart, compact) | Prints branch, changed files and the last check result after compaction |
| \`skills/verify-swift\` | Runs every gate and reports PASS / FAIL with evidence |
| \`agents/swift-reviewer.md\` | Read-only reviewer for a cold second opinion |

Hooks need \`jq\` and a Swift toolchain with \`swift format\` (Xcode 16 or later). They skip projects without a \`Package.swift\`.

Install from a clone of this repo:

\`\`\`
/plugin marketplace add ./02-claude-code
/plugin install $NAME@ios-ai-agent-fundamentals
\`\`\`

Permissions aren't part of a plugin; copy the \`permissions\` block from \`ListingsKit/.claude/settings.json\` into your project settings.
EOF

echo "Packaged $PLUGIN ($VERSION)"
